// Characters the LCD renders differently from what you type
const ROM_ALIASES: Record<string, string> = {
  '\\': YEN,
  '~': RIGHT_ARROW,
  '\u007f': LEFT_ARROW,
}

/**
 * Translates a character into the 5x8 pixel matrix a 16x2 HD44780 LCD shows
 * for it, indexed as `glyph[row][col]` (8 rows × 5 columns, 1 = pixel on).
 * Only the first character of `letter` is used. Characters outside the
 * LiquidCrystal/A00 printable set resolve to a blank cell.
 */
export function resolveLetter(letter: string): LCDGlyph {
  const char = ROM_ALIASES[letter.charAt(0)] ?? letter.charAt(0)
  const rows = FONT[char] ?? FONT[' ']

  return [...rows, '00000'].map((row) =>
    [...row].map((pixel) => (pixel === '1' ? 1 : 0))
  )
}
